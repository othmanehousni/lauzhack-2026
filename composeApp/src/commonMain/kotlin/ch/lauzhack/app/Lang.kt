/** The languages a person reads Molière in, each named in itself. What the presenter says stays English: the ear and
 * the decider know no other, so a hint quotes the English word in the language's own quotation marks. */
enum class Lang(val own: String) {
    En("English"), De("Deutsch"), Fr("Français"), It("Italiano"), Rm("Rumantsch");

    val words: Wording get() = WORDING.getValue(this)

    companion object {
        /** The one a system language code ("de", "rm") names, else English. */
        fun of(code: String?): Lang = entries.firstOrNull { it.name.equals(code, ignoreCase = true) } ?: En
    }
}

/** The language on screen. English until the app chooses one, so scripted runs and tests read English. */
var lang by mutableStateOf(Lang.En)

/** Every word a person reads, in the language on screen. */
val ui: Wording get() = lang.words

private fun String.cap() = replaceFirstChar(Char::uppercase)

